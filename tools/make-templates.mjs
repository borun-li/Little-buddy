// R2 (Q-053/054/055/057): puts fe-ui's art into the page (nothing is copied as a file: the page inlines it). Run: node tools/make-templates.mjs
//  - web/index.html: the 15 <template id="mood-<char>-<mood>"> blocks (every id prefixed "<char>-<mood>--", its clip-path reference too)
//  - web/js/look-art-data.js: item, plant and mannequin markup as strings, so the stage can wear a look at once (no fetch, no flash);
//    since Q-062 also the spark bands, the flare and the stage-up confetti
// Source of truth stays docs/frontend/r2-personalise/evidence/design/. Rerun after fe-ui re-exports.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(root, 'docs/frontend/r2-personalise/evidence/design');
const CHARS = ['honey', 'cotton', 'matcha'];
const MOODS = ['neutral', 'pleasant-high', 'pleasant-low', 'unpleasant-high', 'unpleasant-low'];
const inner = (s) => s.match(/<svg[^>]*>([\s\S]*)<\/svg>/)[1].trim();

let tpls = '<!-- Companion art, one template per character x mood: docs/frontend/r2-personalise/evidence/design/characters/<char>-<mood>.svg\n     (tools/make-templates.mjs), every id prefixed "<char>-<mood>--" (its clip-path reference too) so layers can share the DOM during a crossfade. -->\n';
for (const c of CHARS) for (const m of MOODS) {
  const file = `${c}-${m}.svg`;
  const p = `${c}-${m}--`;
  const body = inner(readFileSync(path.join(SRC, 'characters', file), 'utf8'))
    // 棉棉's ear groups carry a transform attribute that the ear twitch / droop animation would replace: the transform moves to a wrapper
    .replace(/<g id="(ear-(?:left|right))" transform="([^"]+)">([\s\S]*?)<\/g>/g, '<g class="attr-tf" transform="$2"><g id="$1">$3</g></g>')
    .replace(/\bid="([^"]+)"/g, `id="${p}$1"`).replace(/url\(#body-clip\)/g, `url(#${p}body-clip)`);
  tpls += `<template id="mood-${c}-${m}">\n<svg class="companion__art" aria-hidden="true" focusable="false" xmlns="http://www.w3.org/2000/svg" width="400" height="400" viewBox="0 0 400 400" fill="none">\n${body}\n</svg>\n</template>\n`;
}
const htmlPath = path.join(root, 'web/index.html');
let html = readFileSync(htmlPath, 'utf8');
const start = html.indexOf('<!-- Companion art, one template per');
const endMark = html.lastIndexOf('</template>');
if (start < 0 || endMark < 0) throw new Error('template block not found');
html = html.slice(0, start) + tpls.trimEnd() + html.slice(endMark + '</template>'.length);
writeFileSync(htmlPath, html);

// items, plants, the neutral body outline
const strip = (s) => s.replace(/\sid="[^"]*"/g, '');
const core = (s) => s.replace(/^[\s\S]*?<g id="[^"]*">/, '').replace(/<\/g>\s*<\/svg>\s*$/, '');
const items = {};
for (const f of readdirSync(path.join(SRC, 'items')).sort()) {
  if (f.endsWith('.svg')) items[f.replace('.svg', '')] = strip(core(readFileSync(path.join(SRC, 'items', f), 'utf8')));
}
const plants = {};
for (const n of [1, 2, 3]) plants[n] = strip(core(readFileSync(path.join(SRC, 'growth', `plant-${n}.svg`), 'utf8')));
const bodyD = readFileSync(path.join(SRC, 'characters/honey-neutral.svg'), 'utf8').match(/id="body-fur" d="([^"]+)"/)[1];
// Q-062 / DFB-005: the spark bands, the stage-up flare and the confetti + sparkles burst, ids turned into classes (several copies
// can share the page: 成长, the caption, the phone preview); the root <svg> stays with the code (stage-up.js keeps its width/height).
const art = (f) => inner(readFileSync(path.join(SRC, f), 'utf8')).replace(/<!--[\s\S]*?-->/g, '').trim().replace(/\bid="([^"]+)"/g, 'class="$1"');
const sparks = {};
for (const n of [1, 2, 3]) sparks[n] = art(`spark/spark-${n}.svg`);
writeFileSync(path.join(root, 'web/js/look-art-data.js'),
  `// GENERATED by tools/make-templates.mjs from docs/frontend/r2-personalise/evidence/design/{items,growth,spark,stage-up}. Do not edit.\nexport const ITEM_SVG = ${JSON.stringify(items, null, 1)};\nexport const PLANT_SVG = ${JSON.stringify(plants, null, 1)};\nexport const BODY_D = ${JSON.stringify(bodyD)};\n`
  + `export const SPARK_SVG = ${JSON.stringify(sparks, null, 1)};\nexport const FLARE_SVG = ${JSON.stringify(art('spark/spark-flare.svg'))};\nexport const STAGE_UP_SVG = ${JSON.stringify(art('stage-up/confetti.svg'))};\n`);
console.log('templates', CHARS.length * MOODS.length, 'items', Object.keys(items).length);
